"""Generate Revision 10 manuscript values exclusively from archived numeric output."""
from pathlib import Path
import json
import re
from fractions import Fraction
root = Path(__file__).resolve().parents[2]
p = root/'results/gap_check4a/numeric.json'
x = json.loads(p.read_text())
a, h = x['results']['ar1'], x['results']['harmonic']
values = {
    'Prediction': f"{x['prediction_ar1_db']:+.2f}",
    'Five': f"{a['T5|A']['ratios_db']['100-312']:+.1f}",
    'Twenty': f"{a['T20|A']['ratios_db']['625-1250']:+.1f}",
    'TwentyPrior': f"{a['T20|A']['ratios_db']['312-625']:+.1f}",
    'Prior': f"{a['T5|A']['ratios_db']['32-100']:+.1f}",
    'Slope': f"{a['T5|A']['slope_100_312']:.1f}",
    'Diverged': str(h['T5|A']['diverged_seeds']),
    'BiasAr': f"{a['eig']['B_bias_rel_floor_db']:.1f}",
    'BiasHarm': f"{h['eig']['B_bias_rel_floor_db']:.1f}",
    'AMaxAr': f"{a['eig']['A_eig'][-1]:.3f}",
    'AMaxHarm': f"{h['eig']['A_eig'][-1]:.3f}",
    'BMaxAr': f"{a['eig']['B_eig_real'][-1]:.2f}",
    'BMaxHarm': f"{h['eig']['B_eig_real'][-1]:.2f}",
    'Stability': f"{2/a['eig']['A_eig'][-1]:.2f}",
}
summary = (root/'results/gap_check4a/summary.md').read_text()
perseed = (root/'results/gap_check4a_perseed/summary.md').read_text()
pre = re.search(r'seed 300 alone gave about ([+-][0-9.]+) dB \(5 s\) and ([+-][0-9.]+) dB', summary)
seed300 = next(line for line in perseed.splitlines() if line.startswith('| 300 |')).strip('|').split('|')
seed307 = next(line for line in perseed.splitlines() if line.startswith('| 307 |')).strip('|').split('|')
assert pre
values.update(PreFive=pre.group(1), PreTwenty=pre.group(2), SeedThree=seed300[4].strip(), DominantShare=seed307[-1].strip().replace('%', r'\%'))
events = [json.loads(line) for path in sorted((root/'results/final_eval_holdout').glob('det_events_*.jsonl')) for line in path.read_text().splitlines()]
stationary = [r for r in events if r['scen'] == 'S8 stationary']
assert len(stationary) == len({(r['noise'],r['seed']) for r in stationary}) and stationary
values.update(StationaryRuns=str(len(stationary)), StationaryEvents=str(sum(len(r['events']) for r in stationary)))
settings = (root/'paper/v2/supp_tables/settings.tex').read_text()
settings_line = next(line for line in settings.splitlines() if line.startswith('FD-FxNLMS + det &'))
floor = re.search(r'mu\\_min=([0-9.]+)', settings_line)
j = re.search(r'^J & ([0-9]+)', settings, re.M)
assert floor and j
values.update(DetFloor=floor.group(1), DetectorHops=j.group(1))
registered = json.loads((root/'results/gap_check4/numeric.json').read_text())['ratios']['ar1']['pure 1/b schedule (V-SCHED)']
values.update(RegisteredFive=f"{registered['100-312']:+.1f}", RegisteredPrior=f"{registered['32-100']:+.1f}")
rule10b = (root/'docs/current/REVISION_RULE_10b.md').read_text()
old5 = re.search(r'\| A、5 s、100–312 \| ([+-][0-9.]+) dB', rule10b)
old20 = re.search(r'\| A、20 s、625–1250 \| ([+\-−][0-9.]+) dB', rule10b)
assert old5 and old20
values.update(OldFive=old5.group(1), OldTwenty=old20.group(1).replace('−','-'))
scale = re.search(r'scale=([0-9.]+)', settings_line)
assert scale
fraction = Fraction(scale.group(1))
values['DetScale'] = rf'\frac{{{fraction.numerator}}}{{{fraction.denominator}}}'
summary9 = (root/'results/final_eval_holdout/summary.md').read_text()
fail_section = summary9.split('## Failures',1)[1].split('## ',1)[0]
lines = [line for line in fail_section.splitlines() if line.startswith('|')]
cols = [x.strip() for x in lines[0].strip('|').split('|')]
idx = cols.index('harmonic R2')
for key, method in [('FdFails','FD-FxNLMS'),('LeakyFails','leaky FD-FxNLMS'),('RestartFails','FD-FxNLMS + restart')]:
    row = next(line for line in lines if line.startswith('| '+method+' |'))
    values[key] = row.strip('|').split('|')[idx].strip()
values['FailureRuns'] = re.search(r'runs out of (\d+)', fail_section).group(1)
cost = (root/'src/ffanc_norm/cost.py').read_text()
cost_pattern = r'real FFT of length n = ([0-9.]+) n log2 n flops; complex multiply = ([0-9.]+),\s*complex add = ([0-9.]+), real multiply-add = ([0-9.]+)'
matches = re.search(cost_pattern, cost)
sftf = re.search(r'8 M multiplies \+ 8 M adds per sample', cost)
assert matches and sftf
values.update(FFTCount=matches.group(1).rstrip("."), ComplexMult=matches.group(2).rstrip("."), ComplexAdd=matches.group(3).rstrip("."), RealMultAdd=matches.group(4).rstrip("."))
sftfnums = re.search(r'(\d+) M multiplies \+ (\d+) M adds', sftf.group())
values.update(SftfMult=sftfnums.group(1), SftfAdd=sftfnums.group(2), SftfTotal=str(sum(map(int,sftfnums.groups()))))
rule7 = (root/'docs/current/REVISION_RULE_7.md').read_text()
cftf = re.search(r'Cost \(analytic\): about (\d+) M flops', rule7)
assert cftf
values['CftfTotal'] = cftf.group(1)
out = ('% Generated by make_r10_values.py; sources: results/gap_check4a/numeric.json and summary.md,\n'
       '% results/gap_check4a_perseed/summary.md, results/final_eval_holdout/det_events_*.jsonl,\n'
       '% results/gap_check4/numeric.json, final_eval_holdout/summary.md, generated supp_tables/settings.tex,\n'
       '% docs/current/REVISION_RULE_7.md and REVISION_RULE_10b.md, and src/ffanc_norm/cost.py.\n')
out += ''.join('\\newcommand{\\Rten'+name+'}{'+value+'}\n' for name,value in values.items())
(root/'paper/v2/tables/r10_values.tex').write_text(out)
