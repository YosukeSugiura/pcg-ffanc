def _full_vector_future_solution(
    *, x: np.ndarray, disturbance: np.ndarray, secondary_path: np.ndarray,
    y_history: np.ndarray, start: int, stop: int, controller_length: int,
) -> np.ndarray:
    """Unconstrained finite-horizon controller oracle.

    Past controller output y_history[:start] is immutable. The future controller
    output is generated by one constant coefficient vector w over [start, stop).
    The solution minimizes the physical ANC residual over that horizon:

        || d_future + y_s,legacy + R_future w ||_2^2.

    Sensor noise is excluded because it is independent and uncontrollable.
    Minimum-norm least squares is used when the horizon is underdetermined.
    """
    if stop <= start:
        return np.zeros(controller_length, dtype=float)

    # At update time, y_history[start:] has not been generated yet and is zero.
    # Therefore filtering y_history over the future interval gives exactly the
    # immutable secondary-path response due to already emitted controller output.
    legacy = causal_fir_block(y_history, secondary_path, start, stop)
    a = disturbance[start:stop] + legacy
    R = future_controller_to_secondary_matrix(
        x, secondary_path, start, stop, controller_length
    )
    # scipy.linalg.lstsq(gelsy) is substantially faster than an SVD for the many
    # small/medium oracle solves required here, while still handling rank loss.
    w, *_ = lstsq(R, -a, cond=1e-10, lapack_driver='gelsy', check_finite=False)
    return np.asarray(w, dtype=float)


def _controller_geometry(w: np.ndarray, w_star: np.ndarray) -> dict[str, float]:
    den = float(w_star @ w_star)
    if den <= 0.0:
        return {'alpha': 0.0, 'orthogonal_relative': 0.0, 'distance_relative': 0.0, 'norm_ratio': 0.0}
    alpha = float((w @ w_star) / den)
    orth = w - alpha * w_star
    nstar = float(np.sqrt(den))
    return {
        'alpha': alpha,
        'orthogonal_relative': float(np.linalg.norm(orth) / nstar),
        'distance_relative': float(np.linalg.norm(w - w_star) / nstar),
        'norm_ratio': float(np.linalg.norm(w) / nstar),
    }


def _make_signals(cfg: dict, seed: int, extra_hops: int, eval_seconds: float):
    H = int(cfg['hop_length'])
    fs = int(cfg['sample_rate'])
    eval_samples = int(round(eval_seconds * fs))
    n_samples = eval_samples + extra_hops * H

    rng_x = np.random.default_rng(seed)
    rng_v = np.random.default_rng(seed + 1000003)
    x = colored_noise(n_samples, rng_x, pole=float(cfg.get('ar_pole', 0.95)))
    # colored_noise() normalizes by the std of the *whole* extended signal.
    # Renormalize by the evaluation interval so that x[:eval_samples], d and v
    # are sample-for-sample identical to optimize_vss2_robust.make_seed_data()
    # for the same seed.  Oracle and conventional held-out runs are then truly
    # paired (the extra hops only serve future-horizon oracle queries).
    x = x / np.std(x[:eval_samples])
    p = synthetic_primary_path()
    s = synthetic_secondary_path()
    d = np.convolve(x, p, mode='full')[:n_samples]

    # Match the noise variance to the evaluation interval, then extend it using
    # the same variance for future oracle queries.
    d_eval = d[:eval_samples]
    v_eval = secondary_noise_for_snr(d_eval, cfg.get('secondary_noise_snr_db'), rng_v)
    if n_samples > eval_samples:
        pd = float(np.mean(d_eval**2))
        pv = pd / (10.0 ** (float(cfg['secondary_noise_snr_db']) / 10.0))
        v_ext = rng_v.standard_normal(n_samples - eval_samples) * np.sqrt(pv)
        v = np.concatenate([v_eval, v_ext])
    else:
        v = v_eval
    return x, d, v, p, s, eval_samples


def run_method(
    cfg: dict,
    seed: int,
    method: str,
    eval_seconds: float,
    horizon_hops: int = 4,
    mu_cap: float = 4.0,
) -> dict:
    N = int(cfg['fft_length'])
    H = int(cfg['hop_length'])
    M = int(cfg['controller_length'])
    fs = int(cfg['sample_rate'])

    extra_hops = max(horizon_hops, 1)
    x, d, v, p, s, eval_samples = _make_signals(cfg, seed, extra_hops, eval_seconds)
    n_samples = len(x)
    xf = np.convolve(x, s, mode='full')[:n_samples]
    w_star, _, _, _ = wiener_solution(s, p, M, pole=0.95)

    if method == 'known_from_start':
        w = w_star.copy()
    else:
        w = np.zeros(M, dtype=float)

    y = np.zeros(n_samples, dtype=float)
    sec = np.zeros(n_samples, dtype=float)
    e = d + v
    anc = d.copy()

    power = PowerTracker(
        N // 2 + 1,
        float(cfg['power_smoothing']),
        float(cfg['regularization_ratio']),
    )
    synth = synthesis_basis(N, M)
    last_mu_bins = None

    total_power = []
    uncontrolled_power = []
    anc_power = []
    disturbance_power = []
    geometry = []
    scalar_mu = []
    per_bin_mu_first = []

    max_weight_norm_seen = float(np.linalg.norm(w))
    max_abs_error_seen = 0.0

    n_eval_hops = eval_samples // H
    for b in range(n_eval_hops):
        start = b * H
        stop = start + H

        # Physical current hop: coefficients are frozen over the full hop.
        y[start:stop] = causal_fir_block(x, w, start, stop)
        sec[start:stop] = causal_fir_block(y, s, start, stop)
        anc[start:stop] = d[start:stop] + sec[start:stop]
        e[start:stop] = anc[start:stop] + v[start:stop]
        max_abs_error_seen = max(max_abs_error_seen, float(np.max(np.abs(e[start:stop]))))

        total_power.append(float(np.mean(e[start:stop] ** 2)))
        uncontrolled_power.append(float(np.mean((d[start:stop] + v[start:stop]) ** 2)))
        anc_power.append(float(np.mean(anc[start:stop] ** 2)))
        disturbance_power.append(float(np.mean(d[start:stop] ** 2)))

        # Update after observing this hop.
        if method == 'known_from_start':
            pass
        elif method == 'teleport_after_first_hop':
            if b == 0:
                w = w_star.copy()
        elif method == 'fixed_binwise':
            xf_hist = right_aligned_history(xf, stop, N)
            Xf = np.fft.rfft(xf_hist)
            power.update(Xf)
            denom = power.denominator('binwise', b)
            g = fd_block_gradient(xf_hist, e[start:stop], denom, M)
            mu = float(cfg['mu_binwise'])
            w = w - mu * g
            scalar_mu.append(mu)
        elif method == 'scalar_oracle':
            xf_hist = right_aligned_history(xf, stop, N)
            Xf = np.fft.rfft(xf_hist)
            power.update(Xf)
            denom = power.denominator('binwise', b)
            g = fd_block_gradient(xf_hist, e[start:stop], denom, M)
            horizon_stop = min(n_samples, stop + horizon_hops * H)
            mu, _ = _future_cost_and_mu(
                x=x,
                disturbance=d,
                secondary_path=s,
                y_history=y,
                w=w,
                gradient=g,
                start=stop,
                horizon_stop=horizon_stop,
                mu_max=mu_cap,
            )
            w = w - mu * g
            scalar_mu.append(float(mu))
        elif method == 'per_bin_oracle':
            xf_hist = right_aligned_history(xf, stop, N)
            Xf = np.fft.rfft(xf_hist)
            power.update(Xf)
            denom = power.denominator('binwise', b)
            D = per_bin_gradient_basis(xf_hist, e[start:stop], denom, synth)
            horizon_stop = min(n_samples, stop + horizon_hops * H)

            # Future residual with no coefficient update.
            y0 = y.copy()
            y0[stop:horizon_stop] = causal_fir_block(x, w, stop, horizon_stop)
            sec0 = causal_fir_block(y0, s, stop, horizon_stop)
            a = d[stop:horizon_stop] + sec0
            R = future_controller_to_secondary_matrix(x, s, stop, horizon_stop, M)
            B = R @ D
            mu_bins = solve_box_ls(B, a, mu_cap, last_mu_bins)
            w = w - D @ mu_bins
            last_mu_bins = mu_bins
            if b < 5:
                per_bin_mu_first.append(mu_bins.copy())
        elif method.startswith('full_vector_h'):
            L = int(method.split('h')[-1])
            horizon_stop = min(n_samples, stop + L * H)
            w = _full_vector_future_solution(
                x=x,
                disturbance=d,
                secondary_path=s,
                y_history=y,
                start=stop,
                stop=horizon_stop,
                controller_length=M,
            )
        else:
            raise ValueError(f'unknown method: {method}')

        max_weight_norm_seen = max(max_weight_norm_seen, float(np.linalg.norm(w)))
        if b < 8:
            geometry.append(_controller_geometry(w, w_star))

    # Oracles are not assumed stable: they are classified with the same safety
    # limits as the conventional kernels so that a failing oracle can never be
    # reported as a valid primary curve.
    stable, failure = classify_diagnostic_run(
        total_power, uncontrolled_power,
        max_weight_norm=max_weight_norm_seen,
        max_abs_error=max_abs_error_seen,
        disturbance_rms=float(np.sqrt(np.mean(d[:eval_samples] ** 2))),
    )

    return {
        'seed': seed,
        'method': method,
        'stable': stable,
        'failure': failure,
        'max_weight_norm': max_weight_norm_seen,
        'max_abs_error': max_abs_error_seen,
        'hop_length': H,
        'sample_rate': fs,
        'total_power': total_power,
        'uncontrolled_power': uncontrolled_power,
        'anc_power': anc_power,
        'disturbance_power': disturbance_power,
        'geometry_first_8': geometry,
        'scalar_mu_first_20': scalar_mu[:20],
        'per_bin_mu_first_5': [m.tolist() for m in per_bin_mu_first],
    }


def _ensemble_summary(runs: list[dict], cfg: dict, floor_db: float) -> dict:
    H = int(cfg['hop_length'])
    fs = int(cfg['sample_rate'])
    out = {}
    for method in sorted({r['method'] for r in runs}):
        all_rr = [r for r in runs if r['method'] == method]
        status, rr = diagnostic_stability_summary(all_rr)
        if not rr:
            out[method] = status
            continue
        pe = np.asarray([r['total_power'] for r in rr], dtype=float)
        p0 = np.asarray([r['uncontrolled_power'] for r in rr], dtype=float)
        pa = np.asarray([r['anc_power'] for r in rr], dtype=float)
        pd = np.asarray([r['disturbance_power'] for r in rr], dtype=float)

        # Linear powers are averaged across seeds before conversion to dB.
        total_db = ensemble_power_ratio_db(pe, p0)
        anc_db = 10.0 * np.log10(np.maximum(np.mean(pa, axis=0), 1e-300) / np.mean(pd, axis=0))

        thresholds = threshold_times_from_db_curve(
            total_db, H / fs, thresholds=(-3.0, -6.0, -10.0, -15.0, -18.0, -19.0)
        )
        thresholds['floor_plus_0.5db'] = threshold_times_from_db_curve(
            total_db, H / fs, thresholds=(floor_db + 0.5,)
        )[f'{floor_db + 0.5:g}']

        metrics = {
            'ensemble_total_db': total_db.tolist(),
            'ensemble_anc_db': anc_db.tolist(),
            'threshold_times_s': thresholds,
            'cumulative_db': cumulative_power_ratio_db(pe, p0),
            'total_db_first_10': total_db[:10].tolist(),
            'anc_db_first_10': anc_db[:10].tolist(),
        }
        # Same survivor-bias rule as the conventional held-out aggregation:
        # primary metrics only when every seed is stable.
        item = dict(status)
        if status['primary_valid']:
            item.update(metrics)
        else:
            item['stable_only_diagnostic'] = metrics

        if method.startswith('full_vector_h'):
            max_b = min(5, min(len(r['geometry_first_8']) for r in rr))
            geom = []
            for b in range(max_b):
                geom.append({
                    key: float(np.mean([r['geometry_first_8'][b][key] for r in rr]))
                    for key in ('alpha', 'orthogonal_relative', 'distance_relative', 'norm_ratio')
                })
            item['mean_geometry_first_5_updates'] = geom
        if method == 'scalar_oracle':
            n = min(20, min(len(r['scalar_mu_first_20']) for r in rr))
            item['mean_scalar_mu_first_20'] = [
                float(np.mean([r['scalar_mu_first_20'][i] for r in rr])) for i in range(n)
            ]
        if method == 'per_bin_oracle':
            n = min(5, min(len(r['per_bin_mu_first_5']) for r in rr))
            if n:
                item['per_bin_mu_first_5'] = []
                for b in range(n):
                    arr = np.asarray([r['per_bin_mu_first_5'][b] for r in rr], dtype=float)
                    item['per_bin_mu_first_5'].append({
                        'mean': float(np.mean(arr)),
                        'median': float(np.median(arr)),
                        'p90': float(np.percentile(arr, 90)),
                        'max': float(np.max(arr)),
                        'fraction_gt_1': float(np.mean(arr > 1.0)),
                        'fraction_gt_2': float(np.mean(arr > 2.0)),
                    })
        out[method] = item
    return out


def _worker(args):
    return run_method(*args)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--config', default=str(ROOT / 'configs' / 'oracle_2s.json'))
    ap.add_argument('--n-seeds', type=int, default=20)
    ap.add_argument('--seed-start', type=int, default=5000)
    ap.add_argument('--eval-seconds', type=float, default=0.5)
    ap.add_argument('--horizon-hops', type=int, default=4)
    ap.add_argument('--mu-cap', type=float, default=4.0)
    ap.add_argument('--workers', type=int, default=5)
    args = ap.parse_args()

    cfg = json.loads(Path(args.config).read_text(encoding='utf-8'))
    p = synthetic_primary_path()
    s = synthetic_secondary_path()
    M = int(cfg['controller_length'])
    _, _, _, j_min = wiener_solution(s, p, M, pole=0.95)
    var_d = primary_variance(p, pole=0.95)
    snr_db = float(cfg['secondary_noise_snr_db'])
    var_v = var_d / (10.0 ** (snr_db / 10.0))
    floor_db = float(10.0 * np.log10((j_min + var_v) / (var_d + var_v)))

    methods = [
        'known_from_start',
        'teleport_after_first_hop',
        'full_vector_h1',
        'full_vector_h2',
        'full_vector_h4',
        'full_vector_h8',
        'fixed_binwise',
        'scalar_oracle',
        'per_bin_oracle',
    ]

    jobs = []
    for seed in range(args.seed_start, args.seed_start + args.n_seeds):
        for method in methods:
            horizon = args.horizon_hops
            if method.startswith('full_vector_h'):
                horizon = int(method.split('h')[-1])
            jobs.append((cfg, seed, method, args.eval_seconds, horizon, args.mu_cap))

    # Keep BLAS thread counts at one when invoking this script for predictable
    # multiprocessing performance.
    if args.workers <= 1:
        runs = [_worker(job) for job in jobs]
    else:
        with ProcessPoolExecutor(max_workers=args.workers) as ex:
            runs = list(ex.map(_worker, jobs, chunksize=1))

    summary = {
        'conditions': {
            'n_seeds': args.n_seeds,
            'seed_start': args.seed_start,
            'eval_seconds': args.eval_seconds,
            'horizon_hops_scalar_per_bin': args.horizon_hops,
            'per_bin_mu_cap': args.mu_cap,
            'physical_total_floor_db': floor_db,
            'threshold_definition': 'first 16-ms hop of ensemble linear-power mean curve below threshold; no moving average',
        },
        'summary': _ensemble_summary(runs, cfg, floor_db),
    }

    out_dir = ROOT / 'results' / 'transient_oracle_hierarchy'
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / 'summary.json').write_text(json.dumps(summary, indent=2), encoding='utf-8')
    (out_dir / 'runs.json').write_text(json.dumps(runs), encoding='utf-8')
    print(json.dumps(summary, indent=2))


if __name__ == '__main__':
    main()
